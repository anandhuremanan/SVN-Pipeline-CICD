package models

import "time"

// JobStatus represents the execution state of a pipeline build job.
type JobStatus string

const (
	// JobStatusPending indicates job is queued and awaiting execution.
	JobStatusPending JobStatus = "PENDING"
	// JobStatusRunning indicates job is currently executing.
	JobStatusRunning JobStatus = "RUNNING"
	// JobStatusSuccess indicates job completed all build steps successfully.
	JobStatusSuccess JobStatus = "SUCCESS"
	// JobStatusFailed indicates job failed during execution.
	JobStatusFailed JobStatus = "FAILED"
	// JobStatusInterrupted indicates job was interrupted by signal or system shutdown.
	JobStatusInterrupted JobStatus = "INTERRUPTED"
	// JobStatusCancelled indicates job was cancelled prior to completion.
	JobStatusCancelled JobStatus = "CANCELLED"
)

// Job encapsulates a single build execution for a repository revision.
type Job struct {
	// ID is the unique job identifier (e.g. "job-20260805-103500-123").
	ID string `json:"id"`
	// Repository is the target remote repository URL.
	Repository string `json:"repository"`
	// Revision is the SVN revision built by this job.
	Revision string `json:"revision"`
	// Workspace is the absolute path to the build directory.
	Workspace string `json:"workspace"`
	// WorkspaceRetained indicates whether the build directory was preserved on disk.
	WorkspaceRetained bool `json:"workspace_retained"`
	// Status is the current execution state of the job.
	Status JobStatus `json:"status"`
	// StartedAt records when job execution started.
	StartedAt time.Time `json:"started_at"`
	// FinishedAt records when job execution finished.
	FinishedAt time.Time `json:"finished_at"`
	// Duration measures execution runtime duration.
	Duration time.Duration `json:"duration"`
	// StageTimings records execution duration for each pipeline stage.
	StageTimings map[string]time.Duration `json:"stage_timings,omitempty"`
	// DeploymentOutputs maps project names to their permanent published deployment paths.
	DeploymentOutputs map[string]string `json:"deployment_outputs,omitempty"`
	// BuildResults contains project build step details.
	BuildResults []BuildResult `json:"build_results,omitempty"`
	// Artifacts lists outputs generated by the build.
	Artifacts []Artifact `json:"artifacts,omitempty"`
	// ErrorMessage records error description if job execution failed.
	ErrorMessage string `json:"error_message,omitempty"`
}
