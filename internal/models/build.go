package models

import "time"

// BuildStatus represents the outcome status of a project build execution.
type BuildStatus string

const (
	// BuildStatusPending indicates the build has not started.
	BuildStatusPending BuildStatus = "PENDING"
	// BuildStatusRunning indicates the build is currently executing.
	BuildStatusRunning BuildStatus = "RUNNING"
	// BuildStatusSuccess indicates the build completed successfully.
	BuildStatusSuccess BuildStatus = "SUCCESS"
	// BuildStatusFailed indicates the build execution failed.
	BuildStatusFailed BuildStatus = "FAILED"
	// BuildStatusSkipped indicates the build was skipped.
	BuildStatusSkipped BuildStatus = "SKIPPED"
)

// BuildStepResult records the execution outcome of an individual build step.
type BuildStepResult struct {
	// Name is the display name of the step (e.g. "Install Dependencies").
	Name string `json:"name"`
	// Command is the exact binary and args executed.
	Command string `json:"command"`
	// Duration measures execution runtime of this step.
	Duration time.Duration `json:"duration"`
	// Successful indicates if the step finished with exit code 0.
	Successful bool `json:"successful"`
	// ExitCode is the process exit status code.
	ExitCode int `json:"exit_code"`
	// ErrorMessage captures failure details if step failed.
	ErrorMessage string `json:"error_message,omitempty"`
	// StdOut captures standard output for this step.
	StdOut string `json:"stdout,omitempty"`
	// StdErr captures standard error for this step.
	StdErr string `json:"stderr,omitempty"`
}

// BuildResult captures the outcome, step metrics, and generated artifacts for building a single project.
type BuildResult struct {
	// Project is the project metadata that was built.
	Project Project `json:"project"`
	// Status is the final outcome status of the build.
	Status BuildStatus `json:"status"`
	// Duration is the total execution time taken for all build steps.
	Duration time.Duration `json:"duration"`
	// Steps contains detailed execution metrics for each step.
	Steps []BuildStepResult `json:"steps,omitempty"`
	// Artifacts lists outputs generated by the build.
	Artifacts []Artifact `json:"artifacts,omitempty"`
	// StdOut captures cumulative standard output logs.
	StdOut string `json:"stdout,omitempty"`
	// StdErr captures cumulative error output logs.
	StdErr string `json:"stderr,omitempty"`
	// ErrorMessage records string representation of any runtime error encountered.
	ErrorMessage string `json:"error_message,omitempty"`
}
